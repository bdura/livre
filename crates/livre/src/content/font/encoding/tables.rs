#[cfg(test)]
mod tests {
    use livre_font_data::{glyph_list, StandardFont};

    use super::*;

    #[test]
    fn every_name_is_known() {
        let tables: [(&str, &Table); 5] = [
            ("STANDARD", &STANDARD),
            ("WIN_ANSI", &WIN_ANSI),
            ("MAC_ROMAN", &MAC_ROMAN),
            ("MAC_EXPERT", &MAC_EXPERT),
            ("SYMBOL", &SYMBOL),
        ];
        for (table, names) in tables {
            for (code, name) in names.iter().enumerate() {
                if let Some(name) = name {
                    assert!(
                        glyph_list::text(name).is_some(),
                        "{table}[{code:#04X}] = {name:?} is not in the glyph list"
                    );
                }
            }
        }

        // `a1` to `a191` are in Adobe's separate `zapfdingbats.txt`, not in the glyph list.
        for (code, name) in ZAPF_DINGBATS.iter().enumerate() {
            if let Some(name) = name {
                assert!(
                    StandardFont::ZapfDingbats.width(name).is_some(),
                    "ZAPF_DINGBATS[{code:#04X}] = {name:?} is not in ZapfDingbats.afm"
                );
            }
        }
    }

    #[test]
    fn spot_checks() {
        assert_eq!(WIN_ANSI[0x41], Some("A"));
        assert_eq!(WIN_ANSI[0xA0], Some("space"));
        assert_eq!(WIN_ANSI[0xAD], Some("hyphen"));
        assert_eq!(WIN_ANSI[0x80], Some("Euro"));
        assert_eq!(WIN_ANSI[0x81], Some("bullet"));
        assert_eq!(WIN_ANSI[0x8E], Some("Zcaron"));
        assert_eq!(STANDARD[0x27], Some("quoteright"));
        assert_eq!(SYMBOL[0x61], Some("alpha"));
        assert_eq!(ZAPF_DINGBATS[0x21], Some("a1"));
        assert_eq!(ZAPF_DINGBATS[0x61], Some("a60"));
        assert_eq!(MAC_ROMAN[0xCA], Some("space"));
    }
}
